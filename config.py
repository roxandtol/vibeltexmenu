def _deep_merge(base: dict, override: dict) -> dict:
    """Recursively merge *override* into *base* (non-destructive)."""
    merged = base.copy()
    for k, v in override.items():
        if k in merged and isinstance(merged[k], dict) and isinstance(v, dict):
            merged[k] = _deep_merge(merged[k], v)
        else:
            merged[k] = v
    return merged


# ── Public API ──────────────────────────────────────────────────────────────

def base_dir() -> str:
    """Return the directory that contains this script or the executable."""
    if getattr(sys, 'frozen', False):
        return os.path.dirname(sys.executable)
    return os.path.dirname(os.path.abspath(__file__))


def ensure_asset_directories():
    """Ensure that external folders (images, sounds, font, IO) exist next to the executable."""
    root = base_dir()
    for folder in ["images", "sounds", "font", "IO"]:
        fpath = os.path.join(root, folder)
        if not os.path.isdir(fpath):
            os.makedirs(fpath, exist_ok=True)
            print(f"[config] Created missing directory: {fpath}")


def _find_or_autogen(candidates: list[str], template: str, desc: str) -> str:
    """
    Search base_dir() for any of candidates.
    If none exists or the file is empty, write template to candidates[0] and return its path.
    """
    root = base_dir()
    target_path = None

    for name in candidates:
        full = os.path.join(root, name)
        if os.path.isfile(full):
            target_path = full
            break

    if target_path is None:
        target_path = os.path.join(root, candidates[0])
        print(f"[config] {desc} not found; autogenerating default {target_path}")
        try:
            with open(target_path, "w", encoding="utf-8") as f:
                f.write(template)
        except Exception as e:
            print(f"[config] Failed to write {target_path}: {e}")
        return target_path

    # File exists: check if empty (0 bytes or only whitespace)
    try:
        with open(target_path, "r", encoding="utf-8") as f:
            content = f.read().strip()
        if not content:
            print(f"[config] {target_path} is empty; autogenerating default configuration.")
            with open(target_path, "w", encoding="utf-8") as f:
                f.write(template)
    except Exception as e:
        print(f"[config] Error reading {target_path}: {e}")

    return target_path


def load_settings(path: str | None = None) -> dict:
    """Load settings.yaml / settings.yml, autogenerating if missing or empty."""
    ensure_asset_directories()

    if path is None:
        path = _find_or_autogen(
            ["settings.yaml", "settings.yml"],
            SETTINGS_YAML_TEMPLATE,
            "settings configuration"
        )

    user = {}
    if os.path.isfile(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                user = yaml.safe_load(f) or {}
        except Exception as e:
            print(f"[config] Error parsing {path}: {e}; using defaults.")

    return _deep_merge(DEFAULT_SETTINGS, user)


def load_games(path: str | None = None) -> list[dict]:
    """
    Parse games.yaml (or games.yml, game.yaml, game.yml) into a list of game dicts.
    Autogenerates default games.yaml if missing or empty.
    """
    ensure_asset_directories()

    if path is None:
        path = _find_or_autogen(
            ["games.yaml", "games.yml", "game.yaml", "game.yml"],
            GAMES_YAML_TEMPLATE,
            "games configuration"
        )

    raw = {}
    if os.path.isfile(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                raw = yaml.safe_load(f) or {}
        except Exception as e:
            print(f"[config] Error parsing {path}: {e}")

    root = base_dir()
    games: list[dict] = []

    for name, props in raw.items():
        if not isinstance(props, dict):
            continue
        bg_image = props.get("bg image", "")
        sound_sub = props.get("sound subfolder", "")
        bgm = props.get("bgm", "")
        start_sound = props.get("start sound", "")

        bg_image_path = os.path.join(root, "images", bg_image) if bg_image else ""
        bgm_path = os.path.join(root, "sounds", sound_sub, bgm) if (sound_sub and bgm) else ""
        start_sound_path = os.path.join(root, "sounds", sound_sub, start_sound) if (sound_sub and start_sound) else ""

        # Parse launch scripts (numbered dict → ordered list)
        raw_scripts = props.get("launch scripts", {}) or {}
        scripts = []
        for idx in sorted(raw_scripts.keys(), key=lambda k: int(k)):
            entry = raw_scripts[idx]
            scripts.append({
                "name": entry.get("name", f"Script {idx}"),
                "path": entry.get("path", ""),
            })

        game = {
            "name": name,
            "bg_image_path": bg_image_path,
            "sound_subfolder": sound_sub,
            "bgm_path": bgm_path,
            "start_sound_path": start_sound_path,
            "launch_scripts": scripts,
        }
        games.append(game)

        # Warn about missing assets if paths are configured
        if bg_image_path and not os.path.isfile(bg_image_path):
            print(f"[config] WARNING: missing bg image for '{name}': {bg_image_path}")
        if bgm_path and not os.path.isfile(bgm_path):
            print(f"[config] WARNING: missing bgm for '{name}': {bgm_path}")

    print(f"[config] Loaded {len(games)} games from {path}")
    return games
